"""Turn IMU analysis results into configuration snippets."""

from __future__ import annotations

from .imu import ACCEL_AXES, GYRO_AXES, ImuAnalysis


def kalibr_yaml(r: ImuAnalysis, topic: str) -> str:
    aN, aK = r.mean_param(ACCEL_AXES, 'N'), r.mean_param(ACCEL_AXES, 'K')
    gN, gK = r.mean_param(GYRO_AXES, 'N'), r.mean_param(GYRO_AXES, 'K')
    return (
        '# Generated by SensorScope (average of x, y, z)\n'
        '#Accelerometers\n'
        f'accelerometer_noise_density: {aN:.6e}   # [ m / s^2 / sqrt(Hz) ]\n'
        f'accelerometer_random_walk: {aK:.6e}     # [ m / s^3 / sqrt(Hz) ]\n'
        '#Gyroscopes\n'
        f'gyroscope_noise_density: {gN:.6e}       # [ rad / s / sqrt(Hz) ]\n'
        f'gyroscope_random_walk: {gK:.6e}         # [ rad / s^2 / sqrt(Hz) ]\n'
        '\n'
        f'rostopic: {topic}\n'
        f'update_rate: {r.fs:.1f}\n'
    )


def _sdf_axis(axis: str, result) -> str:
    # Gazebo wants per-sample noise: sigma = N * sqrt(rate).
    sigma = result.allan.N * (result.allan.fs**0.5)
    return (
        f'    <{axis}>\n'
        '      <noise type="gaussian">\n'
        '        <mean>0.0</mean>\n'
        f'        <stddev>{sigma:.6e}</stddev>\n'
        '        <bias_mean>0.0</bias_mean>\n'
        f'        <bias_stddev>{result.allan.B:.6e}</bias_stddev>\n'
        '      </noise>\n'
        f'    </{axis}>\n'
    )


def gazebo_imu_sdf(r: ImuAnalysis) -> str:
    out = [
        '<!-- Generated by SensorScope: stddev = N * sqrt(rate), bias_stddev = bias '
        'instability -->\n',
        '<imu>\n',
    ]
    for block, names in (('angular_velocity', GYRO_AXES), ('linear_acceleration', ACCEL_AXES)):
        out.append(f'  <{block}>\n')
        for name in names:
            out.append(_sdf_axis(name[1], r.axes[name]))
        out.append(f'  </{block}>\n')
    out.append('</imu>\n')
    return ''.join(out)
